#!/usr/bin/env node
// Splice zmh-3d's kits into Driving Simulator's index.html, between the
// /*KITS:BEGIN*/ and /*KITS:END*/ markers. The page stays one self-contained
// file; this script is the only thing that writes those lines.
//
//   cd zmhstudio/plugins/zmh-3d/cli
//   python3 -m zmh3d.cli generate-road-kit --seed 42 --emit json --out /tmp/road-kit.json
//   python3 -m zmh3d.cli generate-town-kit --seed 42 --emit json --out /tmp/town-kit.json
//   cd ZackHelms.github.io/games/driving-simulator
//   node build-kits.mjs /tmp/road-kit.json /tmp/town-kit.json
//
// The road kit (road-spec/v1) goes in whole. The town kit (scenery-spec/v1)
// is reduced to what a roadside needs: the buildings (without their furniture),
// the street trees, the forest species, bushes, boulders, and each texture
// recipe's dominant colour. Dependency-free: node's fs only.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const [roadPath, townPath] = process.argv.slice(2);
if (!roadPath || !townPath) { console.error('usage: node build-kits.mjs <road-kit.json> <town-kit.json>'); process.exit(2); }
const road = JSON.parse(readFileSync(roadPath, 'utf8'));
const town = JSON.parse(readFileSync(townPath, 'utf8'));
if (road.format !== 'road-spec/v1') throw new Error('not a road-spec/v1 kit: ' + roadPath);
if (town.format !== 'scenery-spec/v1') throw new Error('not a scenery-spec/v1 kit: ' + townPath);

const strip = b => { const { interior, ...rest } = b; return { ...rest, interior: { lit: interior.lit } }; };
const reduced = {
  seed: town.seed,
  buildings: town.buildings.map(strip),
  trees: town.trees,
  forest: town.surround.forestTrees,
  bushes: town.bushes,
  boulders: town.boulders,
  colors: Object.fromEntries(town.textures.map(t => [t.name, t.colorA])),
};
const block = [
  '/*KITS:BEGIN*/',
  `// GENERATED by build-kits.mjs from zmh-3d road-spec/v1 (seed ${road.seed}) and scenery-spec/v1 (seed ${town.seed}). Do not edit by hand.`,
  `const ROAD_KIT = ${JSON.stringify(road)};`,
  `const TOWN_KIT = ${JSON.stringify(reduced)};`,
  '/*KITS:END*/',
].join('\n');

const page = join(dirname(fileURLToPath(import.meta.url)), 'index.html');
const html = readFileSync(page, 'utf8');
const re = /\/\*KITS:BEGIN\*\/[\s\S]*?\/\*KITS:END\*\//;
if (!re.test(html)) throw new Error('markers not found in ' + page);
const out = html.replace(re, () => block);
writeFileSync(page, out);
console.log(`KITS=${page} road=${JSON.stringify(road).length}B town=${JSON.stringify(reduced).length}B`);
